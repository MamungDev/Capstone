-- Supabase/PostgreSQL schema. The PHP app connects server-side using PDO.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('client', 'artist')),
  email VARCHAR(254) NOT NULL UNIQUE,
  display_name VARCHAR(100) NOT NULL,
  bio VARCHAR(500),
  photo_mime VARCHAR(20),
  photo_data BYTEA,
  password_hash VARCHAR(255),
  google_sub VARCHAR(255) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admin_login_limits (
  bucket CHAR(64) PRIMARY KEY,
  attempts INTEGER NOT NULL CHECK (attempts >= 0),
  window_end BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS client_briefs (
  id CHAR(32) PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES users(id),
  project_name VARCHAR(120) NOT NULL,
  details_json TEXT NOT NULL,
  payload_hash CHAR(64) NOT NULL,
  visual_mime VARCHAR(20),
  visual_data BYTEA,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS client_briefs_owner_created ON client_briefs (client_id, created_at);

CREATE TABLE IF NOT EXISTS app_sessions (
  session_id VARCHAR(128) PRIMARY KEY,
  session_data BYTEA NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS app_sessions_expires ON app_sessions (expires_at);

CREATE TABLE IF NOT EXISTS client_brief_references (
  id CHAR(32) PRIMARY KEY,
  client_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  brief_id CHAR(32) REFERENCES client_briefs(id) ON DELETE CASCADE,
  position INTEGER NOT NULL DEFAULT 0 CHECK (position >= 0),
  name VARCHAR(255) NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('reference', 'sketch')),
  mime VARCHAR(20) NOT NULL,
  image_data BYTEA NOT NULL,
  content_hash CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reference_brief_order ON client_brief_references (brief_id, position);
CREATE INDEX IF NOT EXISTS reference_owner ON client_brief_references (client_id);

CREATE TABLE IF NOT EXISTS brief_access_codes (
  brief_id CHAR(32) PRIMARY KEY REFERENCES client_briefs(id) ON DELETE CASCADE,
  access_code CHAR(32) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS brief_artist_access (
  brief_id CHAR(32) NOT NULL REFERENCES client_briefs(id) ON DELETE CASCADE,
  artist_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (brief_id, artist_id)
);
CREATE INDEX IF NOT EXISTS artist_briefs ON brief_artist_access (artist_id);
